        /// <summary>The names for the game that is open, or nothing when it is not one of these.</summary>
        public static string[] Names()
        {
            string packed;
            try
            {
                packed = DSPRE.RomInfo.gameFamily switch
                {
                    DSPRE.RomInfo.GameFamilies.HGSS => Johto,
                    DSPRE.RomInfo.GameFamilies.Plat => Platinum,
                    DSPRE.RomInfo.GameFamilies.DP => DiamondPearl,
                    _ => null,
                };
            }
            catch { return System.Array.Empty<string>(); }
            return packed == null
                ? System.Array.Empty<string>()
                : packed.Split(' ', System.StringSplitOptions.RemoveEmptyEntries);
        }

        /// <summary>
        /// Which file holds one thing, by the name the game gives it. The number differs per game, so
        /// nothing should hold one of these as a constant.
        ///
        /// A trailing _BIN is ignored on both sides: the headers leave it off palettes and put it on
        /// almost everything else.
        /// </summary>
        public static int Find(string name)
        {
            var names = Names();
            string want = Bare(name);
            for (int i = 0; i < names.Length; i++)
                if (string.Equals(Bare(names[i]), want, System.StringComparison.Ordinal)) return i;
            return -1;
        }

        private static string Bare(string n) =>
            n != null && n.EndsWith("_BIN", System.StringComparison.Ordinal) ? n[..^4] : n;
    }
