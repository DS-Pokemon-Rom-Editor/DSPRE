        /// <summary>The members of a dex, bag, summary or opening movie archive for the open game, or none.</summary>
        public static IReadOnlyList<Entry> For(DirNames dir) => dir switch
        {
            DirNames.PokedexGraphics => GameFamily switch
            {
                GameFamilies.Plat => Platinum,
                GameFamilies.DP => DiamondPearl,
                GameFamilies.HGSS => HeartGold,
                _ => System.Array.Empty<Entry>(),
            },
            DirNames.OpeningDemoGraphics when GameFamily == GameFamilies.HGSS => Opening,
            DirNames.SummaryGraphics => GameFamily switch
            {
                GameFamilies.Plat => SummaryPlatinum,
                GameFamilies.HGSS => SummaryHeartGold,
                _ => System.Array.Empty<Entry>(),
            },
            DirNames.BagGraphics => GameFamily switch
            {
                GameFamilies.Plat => BagPlatinum,
                GameFamilies.DP => BagDiamondPearl,
                GameFamilies.HGSS => BagHeartGold,
                _ => System.Array.Empty<Entry>(),
            },
            _ => System.Array.Empty<Entry>(),
        };

        private static Entry? At(DirNames dir, int index)
        {
            IReadOnlyList<Entry> list = For(dir);
            if (index >= 0 && index < list.Count && list[index].Index == index) return list[index];
            foreach (Entry e in list) if (e.Index == index) return e;
            return null;
        }

        public static string NameOf(DirNames dir, int index) => At(dir, index) is { Name.Length: > 0 } e ? e.Name : null;
        public static string TipOf(DirNames dir, int index) => At(dir, index)?.Tip;

        /// <summary>The drawing an arrangement or cell layout puts together.</summary>
        public static int DrawingFor(DirNames dir, int index)
        {
            if (At(dir, index) is not { } e) return -1;
            if (e.Drawing >= 0) return e.Drawing;
            // A cell layout belongs to the drawing that names it as its cells.
            if (e.Kind != "NCER") return -1;
            foreach (Entry x in For(dir)) if (x.Kind == "NCGR" && x.Cells == index) return x.Index;
            return -1;
        }

        /// <summary>The colours a member is drawn with: its own, or its drawing's.</summary>
        public static int ColoursFor(DirNames dir, int index)
        {
            if (At(dir, index) is not { } e) return -1;
            if (e.Colours >= 0) return e.Colours;
            int drawing = DrawingFor(dir, index);
            return drawing >= 0 && drawing != index ? ColoursFor(dir, drawing) : -1;
        }

        /// <summary>The animation the game plays a cell layout or drawing with, or -1.</summary>
        public static int AnimFor(DirNames dir, int index)
        {
            if (At(dir, index) is not { } e) return -1;
            if (e.Anim >= 0) return e.Anim;
            int drawing = DrawingFor(dir, index);
            return drawing >= 0 && drawing != index && At(dir, drawing) is { Anim: >= 0 } d ? d.Anim : -1;
        }

        /// <summary>The bank of its colours a drawing is painted with, following a layout to its drawing; 0 when the
        /// game uses the first.</summary>
        public static int BankFor(DirNames dir, int index)
        {
            if (At(dir, index) is not { } e) return 0;
            if (e.Bank >= 0) return e.Bank;
            int drawing = DrawingFor(dir, index);
            return drawing >= 0 && drawing != index && At(dir, drawing) is { Bank: >= 0 } d ? d.Bank : 0;
        }

        /// <summary>The first arrangement that lays out a drawing, so the drawing can be shown as the screen it makes.</summary>
        public static int ArrangementFor(DirNames dir, int drawing)
        {
            foreach (Entry e in For(dir))
                if (e.Kind == "NSCR" && e.Drawing == drawing) return e.Index;
            return -1;
        }
