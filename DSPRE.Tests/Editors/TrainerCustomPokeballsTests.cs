        [SkippableTheory]
        [InlineData("IPKE", "DSPRE_TEST_HEARTGOLD")]
        [InlineData("IPKE", "DSPRE_TEST_HEARTGOLD_EU")]
        [InlineData("IPGE", "DSPRE_TEST_SOULSILVER")]
        [InlineData("IPKI", "DSPRE_TEST_HEARTGOLD_ITALIAN")]
        public void AppliesExactAssemblyAndRejectsEveryPartialOrConflictingWrite(string romId, string variable)
        {
            string root = Environment.GetEnvironmentVariable(variable);
            if (variable == "DSPRE_TEST_HEARTGOLD" && string.IsNullOrEmpty(root)) root = TestRoms.HeartGold;
            Skip.If(string.IsNullOrEmpty(root), $"Set {variable} to an unpacked vanilla project.");
            string path = Path.Combine(root, "arm9", "arm9.bin");
            if (!File.Exists(path)) path = Path.Combine(root, "arm9.bin");
            Skip.If(!File.Exists(path), "Vanilla ARM9 fixture unavailable.");
            byte[] original = File.ReadAllBytes(path);
            Assert.Null(TrainerCustomPokeballsPatch.WhyNotApplicable(romId, original));
            byte[] patched = (byte[])original.Clone();
            TrainerCustomPokeballsPatch.Apply(romId, patched);
            Assert.True(TrainerCustomPokeballsPatch.Inspect(romId, patched));
            const int start = TrainerCustomPokeballsPatch.Offset;
            const int end = start + TrainerCustomPokeballsPatch.Length;
            // Fingerprint of independently assembled v1.0.0, not generated by the C# patch builder.
            Assert.Equal("2D06D34572B49C079B18BF2DDC9BF0E1B40B5601AD6CBDA8A5B00D169BBC3C38",
                Convert.ToHexString(SHA256.HashData(patched.AsSpan(start, end - start))));
            Assert.Equal(original[..start], patched[..start]);
            Assert.Equal(original[end..], patched[end..]);
            Assert.Throws<InvalidDataException>(() => TrainerCustomPokeballsPatch.Apply(romId, patched));
            for (int offset = start; offset < end; offset++)
            {
                byte[] conflict = (byte[])original.Clone();
                conflict[offset] ^= 1;
                byte[] before = (byte[])conflict.Clone();
                Assert.Throws<InvalidDataException>(() => TrainerCustomPokeballsPatch.Apply(romId, conflict));
                Assert.Equal(before, conflict);
                byte[] partial = (byte[])patched.Clone();
                partial[offset] ^= 1;
                Assert.False(TrainerCustomPokeballsPatch.Inspect(romId, partial));
            }
            Assert.False(TrainerCustomPokeballsPatch.Inspect("IPKJ", patched));
            Assert.False(TrainerCustomPokeballsPatch.Inspect(romId, patched[..(end - 1)]));
            Assert.Throws<InvalidDataException>(() => TrainerCustomPokeballsPatch.Apply("IPKJ", original));
        }

        private static TrainerPartyMonViewModel NewSlot()
        {
            return new TrainerPartyMonViewModel(0, new ObservableCollection<string>(), new ObservableCollection<string>(),
                new ObservableCollection<string>(Enumerable.Range(0, 501).Select(i => "Item " + i)),
                Array.Empty<string>(), Array.Empty<(int, int)>(), true, true, true, true);
        }

        [Fact]
        public void PickerMapsItemIdsAndSwitchesModesWithoutChangingPartyData()
        {
            TrainerPartyMonViewModel slot = NewSlot();
            slot.BallSeals = 6;
            int changes = 0;
            slot.Changed += (_, _) => changes++;
            slot.ConfigureCapsulePicker(true, Array.Empty<string>());
            Assert.Equal(0, changes);
            Assert.False(slot.HasCapsule);
            Assert.Equal("Pokéball", slot.BallLabel);
            Assert.Equal(6, slot.CapsuleIndex);
            Assert.Equal(6, slot.BallPreviewItemId);
            Assert.Empty(slot.CapsuleStickers);
            slot.CapsuleIndex = 17;
            Assert.Equal(492, slot.BallSeals);
            Assert.Equal(492, slot.BallPreviewItemId);
            Assert.Equal(1, changes);
            slot.CapsuleIndex = 24;
            Assert.Equal(499, slot.BallSeals);
            Assert.Equal(25, slot.CapsuleNames.Count);
            slot.BallSeals = 500;
            Assert.Equal(-1, slot.CapsuleIndex);
            Assert.Equal(-1, slot.BallPreviewItemId);
            Assert.Contains("500", slot.BallValueNote);
            slot.CapsuleIndex = -1; // ComboBox clearing a selection must not clear saved data.
            Assert.Equal(500, slot.BallSeals);
            slot.BallSeals = 0;
            Assert.Equal(4, slot.BallPreviewItemId);
            slot.BallSeals = 6;
            changes = 0;
            slot.ConfigureCapsulePicker(false, Enumerable.Range(0, 10).Select(i => "Capsule " + i).ToArray());
            Assert.Equal(0, changes);
            Assert.True(slot.HasCapsule);
            Assert.Equal("Ball Capsule", slot.BallLabel);
            Assert.Equal(6, slot.CapsuleIndex);
            Assert.Null(slot.BallIcon);
        }

        [Theory]
        [InlineData(false, false)]
        [InlineData(false, true)]
        [InlineData(true, false)]
        [InlineData(true, true)]
        public void BallItemIdRoundTripsInEveryPartyLayout(bool items, bool moves)
        {
            RomInfo.GameFamilies previous = RomInfo.gameFamily;
            try
            {
                typeof(RomInfo).GetProperty(nameof(RomInfo.gameFamily)).SetValue(null, RomInfo.GameFamilies.HGSS);
                foreach (ushort ball in new ushort[] { 0, 6, 16, 492, 499, 500, ushort.MaxValue })
                {
                    PartyPokemon mon = new PartyPokemon(items, moves) { pokeID = 25, level = 30, ballSeals = ball };
                    TrainerProperties properties = new TrainerProperties(0, 1) { chooseItems = items, chooseMoves = moves };
                    byte[] data = mon.ToByteArray();
                    // Party files, unlike individual records, include padding to a four-byte boundary.
                    Array.Resize(ref data, (data.Length + 3) & ~3);
                    Party party = new Party(false, 1, new MemoryStream(data), properties);
                    Assert.Equal(ball, party[0].ballSeals);
                    Assert.Equal(data, party.ToByteArray());
                }
            }
            finally { typeof(RomInfo).GetProperty(nameof(RomInfo.gameFamily)).SetValue(null, previous); }
        }
