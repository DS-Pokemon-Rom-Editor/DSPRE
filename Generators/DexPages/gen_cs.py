"""Writes DexPageRecipes.cs from the page specs in dp_pages.py, pt_pages.py and hg_pages.py. Run: python -B gen_cs.py"""
import json, os
import dp_pages, hg_pages, pt_pages

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "DSPRE.Avalonia", "Avalonia", "Data", "DexPageRecipes.cs")


def s(v):
    return "null" if v is None else json.dumps(v, ensure_ascii=False)


def piece(p):
    return (f"P({p['Screen']}, {p['TileX']}, {p['TileY']}, {p['FromX']}, {p['FromY']}, {p['Width']}, {p['Height']}, "
            f"{p['Palette']}, {p['Fill']}, {s(p['When'])})")


def bg(b):
    pieces = ", ".join(piece(p) for p in b["Pieces"])
    return (f"B({b['Bg']}, {b['Priority']}, {b['Bpp']}, {b['Drawing']}, {b['MapWidth']}, {b['MapHeight']}, "
            f"{b['ScrollX']}, {b['ScrollY']}, {s(b.get('When'))}, new List<ScreenPaste> {{ {pieces} }})")


def pal(p):
    return f"L({p['File']}, {p['ToRow']}, {p['FromRow']}, {p['Rows']}, {s(p['When'])})"


def spr(x):
    return (f"S({s(x['Name'])}, {x['Cells']}, {x['Drawing']}, {x['Anim']}, {x['Seq']}, {x.get('Frame', 0)}, {x['Colours']}, "
            f"{x['Row']}, {x['X']}, {x['Y']}, {x['Priority']}, {x.get('TypeSlot', 0)}, {x.get('TypeDrawing', -1)}, "
            f"{x.get('Width', 0)}, {x.get('Height', 0)}, (DexSizeRole){x.get('Size', 0)}, "
            f"(DexReadout){x.get('Readout', 0)}, {x.get('Step', 0)}, {x.get('Place', 0)}, {s(x['When'])})")


def text(t):
    args = "null" if not t.get("Args") else "new[] { " + ", ".join(s(a) for a in t["Args"]) + " }"
    return (f"T((ScreenTextKind){t['Kind']}, {t['Line']}, {t['Bg']}, {t['X']}, {t['Y']}, (ScreenTextAlign){t['Align']}, "
            f"{t.get('BoxHeight', 0)}, {t['Row']}, {t['Ink']}, {t['Shadow']}, {t['Font']}, {t['Sample']}, {t['Offset']}, "
            f"{t['Colours']}, {t['Priority']}, {t.get('Above', -1)}, {t.get('WinX', 0)}, {t.get('WinY', 0)}, "
            f"{t.get('WinW', 0)}, {t.get('WinH', 0)}, {'true' if t.get('KeepUnder') else 'false'}, {args}, {s(t['When'])})")


def mon(m):
    return (f"M((ScreenMonKind){m['Kind']}, {m['X']}, {m['Y']}, {m['Priority']}, {m.get('Darken', 0)}, "
            f"{m.get('Offset', 0)}, (DexSizeRole){m.get('Size', 0)}, {s(m['When'])})")


def rect(r):
    return f"R({r['Bg']}, {r['X']}, {r['Y']}, {r['Width']}, {r['Height']}, {r['Row']}, {r['Colour']}, {s(r['When'])})"


def screen(sc, indent):
    pad = " " * indent
    lines = [f"new ScreenLayout", f"{pad}{{", f"{pad}    Darken = {sc.get('Darken', 0)},"]
    h = sc.get("Habitat")
    if h is True:
        lines.append(f"{pad}    Habitat = new DexHabitat(),")
    elif isinstance(h, dict):
        fields = ", ".join(f"{k} = {str(v).lower() if isinstance(v, bool) else v}" for k, v in h.items())
        lines.append(f"{pad}    Habitat = new DexHabitat {{ {fields} }},")
    for name, items, fn in (("Bgs", sc["Bgs"], bg), ("Palettes", sc["Palettes"], pal), ("Sprites", sc["Sprites"], spr),
                            ("Texts", sc["Texts"], text), ("Mons", sc["Mons"], mon), ("Rects", sc.get("Rects", []), rect)):
        typ = {"Bgs": "ScreenBg", "Palettes": "ScreenPaletteLoad", "Sprites": "ScreenSprite", "Texts": "ScreenText", "Mons": "ScreenMon",
               "Rects": "ScreenRect"}[name]
        if not items:
            continue
        lines.append(f"{pad}    {name} = new List<{typ}>")
        lines.append(f"{pad}    {{")
        for it in items:
            lines.append(f"{pad}        {fn(it)},")
        lines.append(f"{pad}    }},")
    lines.append(f"{pad}}}")
    return "\n".join(lines)


def game(name, pages):
    out = [f"        private static List<ScreenPage> {name}() => new List<ScreenPage>", "        {"]
    for p in pages:
        variants = ", ".join(s(v) for v in p["Variants"])
        out.append("            new ScreenPage")
        out.append("            {")
        out.append(f"                Id = {s(p['Id'])}, Name = {s(p['Name'])}, MainOnTop = {'true' if p.get('MainOnTop', True) else 'false'},")
        out.append(f"                Variants = new string[] {{ {variants} }},")
        out.append(f"                Main = {screen(p['Main'], 16)},")
        out.append(f"                Sub = {screen(p['Sub'], 16)},")
        out.append("            },")
    out.append("        };")
    return "\n".join(out)


HEADER = '''using System.Collections.Generic;
using static DSPRE.RomInfo;

namespace DSPRE.Avalonia.Data
{
    /// <summary>
    /// Every Pokédex page of DP, Platinum and HGSS as the games put it together: which arrangements, drawings and
    /// colours go on each background, which sprites, text and pictures of the sample Pokémon, and the states a page
    /// can be in. Read from each game's load code (pokediamond, pokeplatinum, pokeheartgold). Generated by
    /// Generators/DexPages/gen_cs.py: change the page specs there and regenerate; don't edit by hand.
    /// </summary>
    public static class DexPageRecipes
    {
        public static IReadOnlyList<ScreenPage> For(GameFamilies family) => family switch
        {
            GameFamilies.DP => DiamondPearl(),
            GameFamilies.Plat => Platinum(),
            GameFamilies.HGSS => HeartGoldSoulSilver(),
            _ => new List<ScreenPage>(),
        };

        private static ScreenPaste P(int screen, int tileX, int tileY, int fromX, int fromY, int width, int height, int palette,
                                  int fill, string when)
            => new ScreenPaste { Screen = screen, TileX = tileX, TileY = tileY, FromX = fromX, FromY = fromY, Width = width,
                              Height = height, Palette = palette, Fill = fill, When = when };

        private static ScreenBg B(int bg, int priority, int bpp, int drawing, int mapWidth, int mapHeight, int scrollX,
                               int scrollY, string when, List<ScreenPaste> pieces)
            => new ScreenBg { Bg = bg, Priority = priority, Bpp = bpp, Drawing = drawing, MapWidth = mapWidth,
                           MapHeight = mapHeight, ScrollX = scrollX, ScrollY = scrollY, When = when, Pieces = pieces };

        private static ScreenPaletteLoad L(int file, int toRow, int fromRow, int rows, string when)
            => new ScreenPaletteLoad { File = file, ToRow = toRow, FromRow = fromRow, Rows = rows, When = when };

        private static ScreenSprite S(string name, int cells, int drawing, int anim, int seq, int frame, int colours, int row,
                                   int x, int y, int priority, int typeSlot, int typeDrawing, int width, int height,
                                   DexSizeRole size, DexReadout readout, int step, int place, string when)
            => new ScreenSprite { Name = name, Cells = cells, Drawing = drawing, Anim = anim, Seq = seq, Frame = frame,
                               Colours = colours, Row = row, X = x, Y = y, Priority = priority, TypeSlot = typeSlot,
                               TypeDrawing = typeDrawing, Width = width, Height = height, Size = size,
                               Readout = readout, Step = step, Place = place, When = when };

        private static ScreenText T(ScreenTextKind kind, int line, int bg, int x, int y, ScreenTextAlign align, int boxHeight, int row,
                                 int ink, int shadow, int font, int sample, int offset, int colours, int priority,
                                 int above, int winX, int winY, int winW, int winH, bool keepUnder, string[] args,
                                 string when)
            => new ScreenText { Kind = kind, Line = line, Bg = bg, X = x, Y = y, Align = align, BoxHeight = boxHeight,
                             Row = row, Ink = ink, Shadow = shadow, Font = font, Sample = sample, Offset = offset,
                             Colours = colours, Priority = priority, Above = above, WinX = winX, WinY = winY,
                             WinW = winW, WinH = winH, KeepUnder = keepUnder, Args = args, When = when };

        private static ScreenRect R(int bg, int x, int y, int width, int height, int row, int colour, string when)
            => new ScreenRect { Bg = bg, X = x, Y = y, Width = width, Height = height, Row = row, Colour = colour, When = when };

        private static ScreenMon M(ScreenMonKind kind, int x, int y, int priority, int darken, int offset, DexSizeRole size,
                                 string when)
            => new ScreenMon { Kind = kind, X = x, Y = y, Priority = priority, Darken = darken, Offset = offset, Size = size,
                            When = when };

'''

if __name__ == "__main__":
    parts = [HEADER]
    for name, module in (("DiamondPearl", dp_pages), ("Platinum", pt_pages), ("HeartGoldSoulSilver", hg_pages)):
        # A JSON round trip turns tuples into lists, as when the specs were kept in JSON.
        parts.append(game(name, json.loads(json.dumps(module.PAGES, ensure_ascii=False))))
        parts.append("")
    parts.append("    }\n}\n")
    open(OUT, "w", encoding="utf-8", newline="\r\n").write("\n".join(parts))
    print("wrote", OUT, sum(1 for _ in open(OUT, encoding="utf-8")), "lines")
